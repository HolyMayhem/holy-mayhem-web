"""Regenerate checked-in sharing images. Requires Python 3 and Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
out=Path('public/images');out.mkdir(parents=True,exist_ok=True)
font_path='/System/Library/Fonts/Supplemental/Arial.ttf'
font_bold='/System/Library/Fonts/Supplemental/Arial Bold.ttf'
for locale,subtitle in [('ru','Приложения. Инструменты. Цифровые сервисы.'),('en','Apps. Tools. Digital services.')]:
 im=Image.new('RGB',(1200,630),(8,9,11));d=ImageDraw.Draw(im)
 for i in range(18):
  points=[]
  theta=math.radians(i*10)
  for step in range(181):
   a=step*2*math.pi/180;x=(45+i*7)*math.cos(a);y=205*math.sin(a)
   points.append((930+x*math.cos(theta)-y*math.sin(theta),310+x*math.sin(theta)+y*math.cos(theta)))
  d.line(points,fill=(58+i*2,53+i*2,77+i*2),width=1)
 d.text((62,65),'INDEPENDENT DEVELOPMENT',font=ImageFont.truetype(font_path,14),fill=(164,157,184))
 f=ImageFont.truetype(font_bold,120)
 d.text((55,140),'HOLY',font=f,fill=(241,240,245),stroke_width=1)
 d.text((55,255),'MAYHEM.',font=f,fill=(241,240,245),stroke_width=1)
 d.text((62,440),subtitle,font=ImageFont.truetype(font_path,23),fill=(166,161,181))
 d.line((62,535,1138,535),fill=(43,42,50))
 d.text((62,560),'TorrServe Silicon     /     TorrFrame     /     HolyVPN',font=ImageFont.truetype(font_path,16),fill=(139,134,155))
 im.save(out/f'og-{locale}.png',optimize=True)

